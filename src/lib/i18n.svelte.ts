/** Stroke names, keyed by their English label in instruments.ts. */
const STROKES_FR: Record<string, string> = {
  'open, accent': 'ouvert, accent',
  open: 'ouvert',
  muted: 'étouffé',
  accent: 'accent',
  hit: 'frappe',
  ghost: 'ghost note',
  rim: 'cercle',
  slap: 'slap',
};

const KEY = 'beats.lang';

function initialLang(): Lang {
  if (typeof document === 'undefined') return 'en'; // tests
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === 'en' || saved === 'fr') return saved;
  } catch {
    /* no storage */
  }
  return navigator.language?.toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

export const i18n = $state({ lang: initialLang() });

if (typeof document !== 'undefined') document.documentElement.lang = i18n.lang;

export function setLang(lang: Lang) {
  i18n.lang = lang;
  if (typeof document === 'undefined') return;
  document.documentElement.lang = lang;
  try {
    localStorage.setItem(KEY, lang);
  } catch {
    /* ignore */
  }
}

export function t(key: Key, params: P = {}): string {
  const msg = (i18n.lang === 'fr' ? fr : en)[key] as Msg;
  if (typeof msg === 'function') return msg(params);
  return msg.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

export function strokeLabel(label: string): string {
  return i18n.lang === 'fr' ? (STROKES_FR[label] ?? label) : label;
}
